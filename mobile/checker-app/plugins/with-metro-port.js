const { withDangerousMod } = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

/**
 * The dev-server port this app uses. worker-app keeps Expo's default 8081.
 * Kept in sync with `--port` in package.json's scripts and RCT_METRO_PORT in
 * .env, which is asserted by src/__tests__/dev-server-port.test.ts.
 */
const METRO_PORT = 8082;

const EXPORT_LINE = `export RCT_METRO_PORT=${METRO_PORT}`;

/**
 * Set RCT_METRO_PORT for builds started from Xcode itself.
 *
 * `RCTBundleURLProvider.mm` compiles the default port in as a constant
 * (`kRCTBundleURLProviderDefaultPort = RCT_METRO_PORT`), fed by
 * React-Core.podspec's `GCC_PREPROCESSOR_DEFINITIONS =>
 * "RCT_METRO_PORT=${RCT_METRO_PORT}"` — an Xcode build-setting reference
 * resolved from the build environment. `expo run:ios` supplies that
 * environment itself (@expo/cli, src/run/ios/XcodeBuild.ts), so it is already
 * correct. Pressing Run in Xcode does not: its environment comes from
 * `ios/.xcode.env`, and without this the app is compiled with the default
 * 8081 and attaches to worker-app's Metro instead of this app's.
 *
 * `ios/` is gitignored and regenerated by `expo prebuild`, so the line cannot
 * simply be committed — it has to be re-applied on every prebuild, which is
 * what this plugin does.
 */
function withMetroPort(config) {
  return withDangerousMod(config, [
    'ios',
    async (cfg) => {
      const file = path.join(cfg.modRequest.platformProjectRoot, '.xcode.env');
      const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
      fs.writeFileSync(file, applyMetroPort(existing));
      return cfg;
    },
  ]);
}

/**
 * Pure half, so the transform is testable without a prebuild: replaces an
 * existing RCT_METRO_PORT export rather than appending a second one (the last
 * assignment would win, but two conflicting lines in a generated file is how
 * this gets "fixed" back to 8081 by the next person reading it).
 */
function applyMetroPort(contents) {
  const line = /^export RCT_METRO_PORT=.*$/m;
  if (line.test(contents)) {
    return contents.replace(line, EXPORT_LINE);
  }
  const base = contents.endsWith('\n') || contents === '' ? contents : `${contents}\n`;
  return `${base}${EXPORT_LINE}\n`;
}

module.exports = withMetroPort;
module.exports.applyMetroPort = applyMetroPort;
module.exports.METRO_PORT = METRO_PORT;
